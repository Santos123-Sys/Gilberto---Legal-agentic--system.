"""Private, content-addressed object storage for original documents.

Objects are addressed by ``<tenant_id>/<sha256>``. Keys are generated by the
server and validated strictly, so a caller cannot traverse directories, read
another tenant's object, or address an object by an arbitrary name. Reads
re-verify the content hash. There is no public URL interface by design.

Only a local filesystem backend exists in PR-02. A private bucket backend
must implement the same interface and pass the same tests before use.
"""
from __future__ import annotations

import os
import re
import tempfile
from pathlib import Path

from .provenance import sha256_bytes

_TENANT = re.compile(r"^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$")
_DIGEST = re.compile(r"^[0-9a-f]{64}$")


class ObjectKeyError(ValueError):
    pass


class ObjectAccessDenied(PermissionError):
    pass


class ObjectIntegrityError(RuntimeError):
    pass


def object_key(tenant_id: str, digest: str) -> str:
    if not isinstance(tenant_id, str) or not _TENANT.match(tenant_id):
        raise ObjectKeyError("invalid tenant identifier")
    if not isinstance(digest, str) or not _DIGEST.match(digest):
        raise ObjectKeyError("invalid content digest")
    return f"{tenant_id}/{digest}"


def parse_key(key: str) -> tuple[str, str]:
    if not isinstance(key, str) or key.count("/") != 1:
        raise ObjectKeyError("malformed object key")
    tenant_id, digest = key.split("/")
    object_key(tenant_id, digest)  # validates both parts
    return tenant_id, digest


class LocalPrivateObjectStore:
    def __init__(self, root: str | os.PathLike):
        self.root = Path(root).resolve()
        self.root.mkdir(mode=0o700, parents=True, exist_ok=True)
        os.chmod(self.root, 0o700)

    def _path(self, key: str) -> Path:
        tenant_id, digest = parse_key(key)
        path = (self.root / tenant_id / digest).resolve()
        if self.root not in path.parents:
            raise ObjectKeyError("object key escapes the store")
        return path

    def put(self, tenant_id: str, data: bytes) -> str:
        """Store bytes for a tenant; returns the server-generated key.
        Writing identical content twice is idempotent."""
        key = object_key(tenant_id, sha256_bytes(data))
        path = self._path(key)
        if path.exists():
            return key
        path.parent.mkdir(mode=0o700, exist_ok=True)
        fd, tmp = tempfile.mkstemp(dir=path.parent)
        try:
            with os.fdopen(fd, "wb") as handle:
                handle.write(data)
                handle.flush()
                os.fsync(handle.fileno())
            os.chmod(tmp, 0o600)
            os.replace(tmp, path)
        except BaseException:
            if os.path.exists(tmp):
                os.unlink(tmp)
            raise
        return key

    def get(self, tenant_id: str, key: str) -> bytes:
        """Read an object only on behalf of the tenant that owns it."""
        owner, digest = parse_key(key)
        if owner != tenant_id:
            raise ObjectAccessDenied("object is not available to this tenant")
        path = self._path(key)
        if not path.is_file():
            raise FileNotFoundError("object not found")
        data = path.read_bytes()
        if sha256_bytes(data) != digest:
            raise ObjectIntegrityError("stored object does not match its content hash")
        return data
